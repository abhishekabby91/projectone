#!/usr/bin/env node
/**
 * Regenerates `docs/ROUTE-INVENTORY.md` — the list of what already exists.
 *
 * This exists because `docs/NEW-PAGE-BRIEF.md` asks an external AI to judge
 * whether a proposed page duplicates an existing intent, and to prefer
 * deepening an existing page over adding a new one. Both are unexecutable
 * without knowing what the site already has: an assistant working outside this
 * repo cannot see the 204 routes it is being asked to compare against, so it
 * agrees with the rule and cannot apply it. The inventory is what makes that
 * section real.
 *
 *   node scripts/route-inventory.mjs
 *
 * Re-run it whenever routes are added or removed, and paste the output file
 * alongside the brief. Its route count should match what
 * `scripts/verify-pages.mjs` reports as checked; if they disagree, regenerate
 * this rather than trusting it.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { readdir } from 'node:fs/promises';
import { join, relative } from 'node:path';

/** Permanent redirect sources — their destinations are the real URLs. */
const REDIRECT_SOURCES = new Set([
  '/blog/hoa-delinquency-accounting',
  '/blog/hoa-monthly-close-process',
  '/blog/hoa-vendor-invoice-processing',
  '/blog/hoa-year-end-checklist',
]);

/** Deliberately not indexable, so not candidates for overlap either. */
const NOINDEX = new Set(['/technology/myob', '/thank-you']);

async function pageFiles(dir, acc = []) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) await pageFiles(full, acc);
    else if (entry.name === 'page.tsx') acc.push(full);
  }
  return acc;
}

/**
 * The page's own metadata title. Matched against `title:` in the genMeta call
 * rather than the h1, because the title is the SERP-facing phrasing and so the
 * better signal for whether two pages are chasing one query.
 */
function titleOf(source) {
  const m =
    source.match(/title:\s*'((?:[^'\\]|\\.)*)'/) ||
    source.match(/title:\s*"((?:[^"\\]|\\.)*)"/);
  return m ? m[1].replace(/\\'/g, "'").replace(/\\"/g, '"') : '';
}

const rows = [];
for (const file of await pageFiles('app')) {
  const dir = relative('app', file).replace(/\/?page\.tsx$/, '');
  const route = dir === '' ? '/' : `/${dir}`;
  if (REDIRECT_SOURCES.has(route) || NOINDEX.has(route)) continue;
  rows.push([route, titleOf(readFileSync(file, 'utf8'))]);
}
rows.sort(([a], [b]) => (a < b ? -1 : 1));

const out = `# Route inventory — what already exists

**Generated by \`node scripts/route-inventory.mjs\`. Do not hand-edit.**

Paste this alongside \`docs/NEW-PAGE-BRIEF.md\`. Without it, §11 of that brief
is unexecutable: an assistant cannot tell whether a proposed page duplicates an
existing intent, and "prefer improving an existing page" becomes a rule it can
agree with and never apply.

${rows.length} indexable routes. Excludes the ${REDIRECT_SOURCES.size} permanent
redirect sources and the ${NOINDEX.size} noindex routes, since neither is a
candidate for overlap.

| Route | Page title |
|---|---|
${rows.map(([r, t]) => `| \`${r}\` | ${t.replace(/\|/g, '\\|')} |`).join('\n')}
`;

writeFileSync('docs/ROUTE-INVENTORY.md', out);
console.log(`wrote docs/ROUTE-INVENTORY.md — ${rows.length} indexable routes`);
